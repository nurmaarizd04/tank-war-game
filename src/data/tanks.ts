import type { FlagCode } from "./flags";

export type Era = "modern" | "ww2";
export type CamoType = "blobs" | "stripes" | "digital" | "plain";
export type TurretShape = "box" | "wedge" | "long" | "dome" | "cast";

export interface TankLook {
  /** Panjang & lebar badan (unit dunia game) */
  length: number;
  width: number;
  /** [warna dasar, kamuflase 1, kamuflase 2] */
  colors: [string, string, string];
  camo: CamoType;
  turret: TurretShape;
  turretScale: number;
  /** Posisi turret di sepanjang badan (negatif = ke belakang) */
  turretOffset: number;
  barrel: number;
  barrelWidth: number;
  muzzleBrake: boolean;
  /** Mesin di depan (Merkava) */
  frontEngine?: boolean;
  /** Blok armor reaktif (ERA) di turret */
  era?: boolean;
  /** Paku keling ala tank Perang Dunia II */
  rivets?: boolean;
}

export interface TankModel {
  id: string;
  name: string;
  country: string;
  flag: FlagCode;
  era: Era;
  year: number;
  description: string;
  hp: number;
  /** Pengurangan kerusakan 0–1 */
  armor: number;
  /** Kecepatan maksimum (unit/detik) */
  speed: number;
  /** Kecepatan putar badan & turret (radian/detik) */
  hullTurn: number;
  turretTurn: number;
  damage: number;
  /** Waktu isi ulang (detik) */
  reload: number;
  shellSpeed: number;
  range: number;
  look: TankLook;
  /**
   * Tank rahasia: tersembunyi sampai dibuka dengan kode, tidak dipakai lawan komputer.
   * "gold"/"silver" berlapis logam mengilap; "hidden" menyamar persis seperti tank biasa.
   */
  secret?: "gold" | "silver" | "hidden";
}

