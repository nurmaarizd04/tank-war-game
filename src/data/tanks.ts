/** Tank yang tersedia untuk semua orang & lawan komputer (tanpa tank rahasia) */
export const STANDARD_TANKS = TANKS.filter((t) => !t.secret);

export const tankById = (id: string) => TANKS.find((t) => t.id === id) ?? TANKS[0];

/** Hash FNV-1a: kode rahasia tidak ditulis apa adanya di kode sumber */
function hashCode(text: string) {
  let h = 0x811c9dc5;
  for (const c of text) h = Math.imul(h ^ c.charCodeAt(0), 0x01000193) >>> 0;
  return h;
}

/** Hash kode rahasia → id tank yang dibuka */
const SECRET_CODES: Record<number, string> = {
  796724727: "garuda-x1",
  669089267: "rajawali-x2",
  3658736598: "harimau-k",
};

/** Tank rahasia yang dibuka oleh kode ini, atau undefined bila kodenya salah */
export function secretTankForCode(code: string) {
  const id = SECRET_CODES[hashCode(code.trim().toLowerCase())];
  return id ? tankById(id) : undefined;
}

/** Nilai 0–1 untuk bar statistik di garasi */
export function tankRatings(t: TankModel) {
  const norm = (v: number, min: number, max: number) => Math.max(0.08, Math.min(1, (v - min) / (max - min)));
  return {
    firepower: norm(t.damage / t.reload, 14, 28),
    armor: norm(t.hp * (1 + t.armor), 170, 360),
    mobility: norm(t.speed, 65, 140),
    reload: norm(1 / t.reload, 1 / 3.1, 1 / 1.45),
  };
}
